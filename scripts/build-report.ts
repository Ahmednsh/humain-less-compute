/**
 * Builds results/report.md and results/report.html from the committed run logs.
 * usage: npx tsx scripts/build-report.ts
 */
import { existsSync, writeFileSync } from 'node:fs';
import { readRunRows } from '../src/eval/run.js';
import { summarize } from '../src/eval/metrics.js';
import { renderMarkdown, renderHtmlSections, type NamedSummary, type ReportSection } from '../src/eval/report.js';
import { POLICY_LABELS, type PolicyName } from '../src/config.js';

const R = 'results/runs';
const row = (file: string, labelOverride?: string): NamedSummary | null => {
  const path = `${R}/${file}.jsonl`;
  if (!existsSync(path)) return null;
  const rows = readRunRows(path);
  const name = rows[0]?.policy ?? file;
  return { name, label: labelOverride ?? `${POLICY_LABELS[name as PolicyName] ?? ''} · ${file}`, s: summarize(rows) };
};
const rows = (...specs: (string | [string, string])[]) => specs.map(s => (typeof s === 'string' ? row(s) : row(s[0], s[1]))).filter((x): x is NamedSummary => x !== null);

const sections: ReportSection[] = [
  {
    title: 'Ablation ladder — dev set (150 tasks, 50 per tier)',
    note: 'Baseline P0 = claude-sonnet-5.5 on every question with the full 12-table schema, glossary and 9 examples. Small tier = meta-llama/llama-3.3-70b-instruct (bake-off, D-017). θ = 4 (sweep, D-018). P2 and P3 are iteration 2 (D-019); iteration-1 rows are in EXPERIMENTS.md.',
    baselineName: 'P0',
    rows: rows('dev-P0', 'dev-S', ['dev-P1-theta4', '+ router · dev-P1-theta4'], 'dev-P2', 'dev-P3', 'dev-V'),
  },
  {
    title: 'Held-out set — 150 unseen tasks incl. 6 never-seen question types, generated with a secret seed outside the repository, run once after freezing all thresholds',
    note: 'Nobody looked at these tasks or their answers; only this aggregate was read.',
    baselineName: 'P0',
    rows: rows('holdout-P0', 'holdout-P3'),
  },
  {
    title: 'Robustness — the full system (P3) under changed conditions, no retuning (first 60 tasks of each 90-task set)',
    note: 'R1: tables and columns renamed (customers→clients, orders→sales_orders, order_items→sales_order_lines, unit_price→price_per_unit, …). R2: the same question types phrased in Arabic. R3: the small tier swapped for qwen/qwen3.7-flash. The dev-set P3 row and, where budget allowed, a P0 row on the same set give the reference.',
    baselineName: 'P0',
    rows: rows(['r1_renamed-P0', 'P0 on renamed schema · r1_renamed-P0'], ['r1_renamed-P3', 'R1 renamed schema · r1_renamed-P3'], ['r2_arabic-P3', 'R2 Arabic questions · r2_arabic-P3'], ['r3_modelswap-P3', 'R3 reference (llama small) · r3_modelswap-P3'], ['r3_modelswap-P3-small-qwen-qwen3.7-flash', 'R3 small = qwen3.7-flash · r3_modelswap-P3-small-qwen']),
  },
];

const md = sections.map(sec => `## ${sec.title}\n\n${sec.note ? sec.note + '\n\n' : ''}${renderMarkdown(sec.rows, sec.baselineName)}`).join('\n\n');
writeFileSync('results/report.md', `# Results\n\nGenerated by \`npx tsx scripts/build-report.ts\` from the logs in \`results/runs/\`. One row per policy; every number is computed from the per-task JSONL rows (see \`src/eval/metrics.ts\`).\n\n${md}\n`);
writeFileSync('results/report.html', renderHtmlSections(sections));
console.log('wrote results/report.md and results/report.html');
